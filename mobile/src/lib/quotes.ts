// Merge: original lines (no author) + famous lines (with author) + extra lines
// (no author). IDs stay stable: QUOTES 0-39, FAMOUS 40-49, EXTRA 50-364,
// giving exactly 365 unique quotes - one per day of a non-leap year.
const ALL: Quote[] = [
  ...QUOTES.map((text, i) => ({ id: i, text, author: null })),
  ...FAMOUS.map(([text, author], i) => ({ id: QUOTES.length + i, text, author })),
  ...EXTRA.map((text, i) => ({ id: QUOTES.length + FAMOUS.length + i, text, author: null })),
];

// Deterministic daily pick: same quote for everyone on a given calendar day.
// With 365 quotes, dayOfYear 1..365 maps 1:1 onto every quote (no repeats
// within a year); a leap-year day 366 wraps back to the day-1 quote.
export function quoteOfTheDay(): Quote {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((now.getTime() - start.getTime()) / 86400000);
  const idx = dayOfYear % ALL.length;
  return { ...ALL[idx] };
}

// Look up any quote by its merged-array id (used by favourites).
export function quoteById(id: number): Quote {
  const q = ALL[id];
  return q ? { ...q } : { id, text: '', author: null };
}
